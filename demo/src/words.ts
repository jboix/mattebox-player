/** The attributes a control takes in a language, by its tag. */
export function attributesFor(tag: string, words: Words): Readonly<Record<string, string>> {
  switch (tag) {
    case 'mbx-start-button':
      return { 'label-play': words.play, 'label-replay': words.replay };
    case 'mbx-error-screen':
      return { 'label-title': words.errorTitle, 'label-retry': words.retry };
    case 'mbx-play-button':
      return { 'label-play': words.play, 'label-pause': words.pause, 'label-replay': words.replay };
    case 'mbx-mute-button':
      return { 'label-mute': words.mute, 'label-unmute': words.unmute };
    case 'mbx-volume-slider':
      return { label: words.volume };
    case 'mbx-seek-bar':
      return { label: words.seek, 'label-of': words.of, 'label-behind': words.behind };
    case 'mbx-live-button':
      return { text: words.live, 'label-live': words.goLive, 'label-at-edge': words.atEdge };
    case 'mbx-speed-menu':
      return { label: words.speed, 'label-normal': words.normal, 'label-back': words.back };
    case 'mbx-quality-menu':
      return { label: words.quality, 'label-auto': words.auto, 'label-back': words.back };
    case 'mbx-audio-menu':
      return { label: words.audio, 'label-back': words.back };
    case 'mbx-subtitles-menu':
      return {
        label: words.subtitles,
        'label-back': words.back,
        'label-off': words.off,
        'label-track': words.track,
        'label-settings': words.settings,
        'label-size': words.size,
        'label-background': words.background,
        'label-small': words.small,
        'label-medium': words.medium,
        'label-large': words.large,
        'label-xlarge': words.xlarge,
        'label-none': words.none,
        'label-dark': words.dark,
        'label-solid': words.solid,
      };
    case 'mbx-drm-badge':
      return {
        label: words.protectedBy,
        'label-key': words.key,
        'label-keys': words.keys,
        'label-no-key': words.noKey,
      };
    case 'mbx-pip-button':
      return { 'label-enter': words.pipEnter, 'label-exit': words.pipExit };
    case 'mbx-fullscreen-button':
      return { 'label-enter': words.fsEnter, 'label-exit': words.fsExit };
    default:
      return {};
  }
}
