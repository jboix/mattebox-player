/**
 * Every word the controls show, per language, as the attributes each
 * control takes. English is the element's default and needs no attribute;
 * the rest are a set of them, which is all a language is to the element.
 * The order of the controls never changes with the language: a page that
 * wants a mirrored bar for Arabic writes it mirrored.
 */

export interface Words {
  readonly play: string;
  readonly pause: string;
  readonly replay: string;
  readonly mute: string;
  readonly unmute: string;
  readonly volume: string;
  readonly seek: string;
  /** With `{current}` and `{duration}`. */
  readonly of: string;
  /** With `{time}`. */
  readonly behind: string;
  readonly live: string;
  readonly goLive: string;
  readonly atEdge: string;
  readonly speed: string;
  readonly normal: string;
  /** With `{page}`. */
  readonly back: string;
  readonly quality: string;
  readonly auto: string;
  readonly audio: string;
  readonly subtitles: string;
  readonly off: string;
  readonly track: string;
  readonly settings: string;
  readonly size: string;
  readonly background: string;
  readonly small: string;
  readonly medium: string;
  readonly large: string;
  readonly xlarge: string;
  readonly none: string;
  readonly dark: string;
  readonly solid: string;
  /** With `{system}` and `{keys}`. */
  readonly protectedBy: string;
  /** With `{count}` and `{statuses}`. */
  readonly key: string;
  readonly keys: string;
  readonly noKey: string;
  readonly pipEnter: string;
  readonly pipExit: string;
  readonly fsEnter: string;
  readonly fsExit: string;
  readonly errorTitle: string;
  readonly retry: string;
  /** With `{seconds}`. */
  readonly skipBack: string;
  readonly skipForward: string;
}

export interface Language {
  readonly name: string;
  readonly words: Words;
}

